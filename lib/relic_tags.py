def apply_relic_tags(relics) -> tuple[int, int]:
    """修正遗物标签 (原地修改), 返回 (补空条数, 覆盖修正条数)。"""
    filled = fixed = 0
    for e in relics:
        rid = int(e.get("id", 0))
        if rid in FIX_RELIC_TAGS:
            want = list(FIX_RELIC_TAGS[rid])
            if list(e.get("tags") or []) != want:
                e["tags"] = want
                fixed += 1
            continue
        if e.get("tags"):
            continue
        extra = EXTRA_RELIC_TAGS.get(rid)
        if not extra:
            continue
        e["tags"] = list(extra)
        filled += 1
    return filled, fixed
